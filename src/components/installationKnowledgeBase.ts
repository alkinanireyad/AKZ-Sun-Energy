export function getSmartResponse(userInput: string): string {
  const lowerInput = userInput.toLowerCase();
  
  // Normalize Arabic
  const normalized = lowerInput
    .replace(/أ|إ|ا/g, 'ا')
    .replace(/ى/g, 'ي')
    .trim();
  
  // Score-based matching
  let bestMatch: any = null;
  let bestScore = 0;
  
  for (const item of INSTALLATION_KNOWLEDGE_BASE) {
    let matchCount = 0;
    let hasHighPriorityMatch = false;
    
    for (const keyword of item.keywords) {
      const keywordNorm = keyword
        .replace(/أ|إ|ا/g, 'ا')
        .replace(/ى/g, 'ي');
      
      if (normalized.includes(keywordNorm)) {
        matchCount++;
        if (keyword.length > 3) {
          hasHighPriorityMatch = true;
        }
      }
    }
    
    const priority = item.priority || 5;
    const priorityBonus = hasHighPriorityMatch ? 5 : 0;
    const score = (matchCount * 10) + (priority * 2) + priorityBonus;
    
    if (score > bestScore) {
      bestScore = score;
      bestMatch = item;
    }
  }
  
  if (bestMatch && bestScore > 0) {
    return bestMatch.response;
  }
  
  return `📚 اسأل عن:
🔌 إعدادات إنفرتر مع بطاريات
⚡ حساب الكابلات والفيوزات
🔋 أنواع البطاريات
🎯 استكشاف الأعطال
💰 حسابات التكاليف
☀️ الطاقة الشمسية في العراق

كن محدداً قدر الإمكان!`;
}
